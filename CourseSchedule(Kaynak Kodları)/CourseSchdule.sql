create table Faculties(
	FacultyID int primary key identity(1,1),
	FacultyName nchar(20) not null)

create table Departments(
	DepartmentID int primary key identity(1,1),
	DepartmentName nvarchar(30) not null,
	FacultyID int not null,
    foreign key (FacultyID) references Faculties(FacultyID))

create table tbl_Hours(
	HourID int primary key identity(1,1),
	HourInterval nvarchar(50) not null,
	OrderNo int not null)

create table tbl_Days(
	DayID int primary key identity(1,1),
	DayTitle nchar(20) not null)

create table Classrooms(
	ClassroomID int primary key identity(1,1),
	ClassroomName nchar(20) not null,
	Capacity int not null,
	ClassType nvarchar(20) not null)

create table Teachers(
	TeacherID int primary key identity(1,1),
	DepartmentID int not null,
	NameSurname nvarchar(20) not null,
	Title nvarchar(20) not null,
	foreign key (DepartmentID) references Departments(DepartmentID))

create table Lessons(
	LessonID int primary key identity(1,1),
	Duration int not null,
	DepartmentID int not null,
	LessonType nvarchar(20) not null,
	LessonName nvarchar(20) not null,
	Credit int not null,
	foreign key (DepartmentID) references Departments(DepartmentID))

create table StudentsGroups(
	GroupID int primary key identity(1,1),
	GroupName nvarchar(20) not null,
	NumberofPeople int not null,
	DepartmentID int not null,
	foreign key (DepartmentID) references Departments(DepartmentID))

create table TeacherLessons(
	TeacherLessonID int primary key identity(1,1),
	TeacherID int not null,
	LessonID int not null,
	foreign key (TeacherID) references Teachers(TeacherID),
	foreign key (LessonID) references Lessons(LessonID))

create table TeacherAvailability(
	UnID int primary key identity(1,1),
	TeacherID int not null,
	DayID int not null,
	HourID int not null,
	AvailabilityStatus bit not null,
	foreign key (TeacherID) references Teachers(TeacherID),
	foreign key (DayID) references tbl_Days(DayID),
	foreign key (HourID) references tbl_Hours(HourID))

create table GroupLessons(
	GroupLessonID int primary key identity(1,1),
	WeeklyCount int not null,
	LessonID int not null,
	GroupID int not null,
	foreign key (LessonID) references Lessons(LessonID),
	foreign key (GroupID) references StudentsGroups(GroupID))

create table CourseSchedule(
	ScheduleID int primary key identity(1,1),
	GroupID int not null,
	LessonID int not null,
	HourID int not null,
	DayID int not null,
	ClassroomID int not null,
	TeacherID int not null,
	IsLocked bit not null,
	IsAutoGenerated bit not null,
	foreign key (GroupID) references StudentsGroups(GroupID),
	foreign key (LessonID) references Lessons(LessonID),
	foreign key (HourID) references tbl_Hours(HourID),
	foreign key (DayID) references tbl_Days(DayID),
	foreign key (TeacherID) references Teachers(TeacherID),
	foreign key (ClassroomID) references Classrooms(ClassroomID))
